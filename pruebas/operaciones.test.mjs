import assert from 'node:assert/strict';
import {initialData,applyOperation,bucketRentals,loadData} from '../src/logica/operacion/operaciones.js';
let data=initialData();
const original=JSON.stringify(data);
assert.equal(bucketRentals(data,'apartados').length,4);
assert.throws(()=>applyOperation(data,'R-013','deliver',{date:'2026-10-22',receiver:'Cliente'}));
data=applyOperation(data,'R-013','prepare',{mechanic:'Mecánico de ejemplo',notes:'Verificación completa',result:'ready',inventory:['Extintor']});
assert.equal(data.units[0].state,'En preparación');
const deliveredWithoutDocument=applyOperation(data,'R-013','deliver',{date:'2026-10-22',receiver:'Cliente'});
assert.equal(deliveredWithoutDocument.rentals[0].status,'En renta');
assert.equal(deliveredWithoutDocument.units[0].state,'En renta');
assert.equal(deliveredWithoutDocument.rentals[0].delivery.receiver,'Cliente');
assert.ok(!deliveredWithoutDocument.rentals[0].document&&!deliveredWithoutDocument.rentals[0].documentPhoto);
const attachedAfterDelivery=applyOperation(deliveredWithoutDocument,'R-013','photo',{image:'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=',name:'responsiva.png',date:'2026-10-23'});
assert.equal(attachedAfterDelivery.rentals[0].documentPhoto.name,'responsiva.png');
assert.equal(attachedAfterDelivery.rentals[0].status,'En renta');
assert.equal(attachedAfterDelivery.rentals[0].delivery.date,'2026-10-22');
assert.equal(attachedAfterDelivery.rentals[0].signature,null,'Adjuntar una foto no confirma una firma');
assert.deepEqual(loadData({getItem:()=>JSON.stringify(attachedAfterDelivery)}),attachedAfterDelivery);
assert.equal(data.rentals[0].status,'En preparación','La operación no modifica los datos originales');
data=applyOperation(data,'R-013','document',{hours:'150',inventory:['Extintor'],date:'2026-10-22'});
data=applyOperation(data,'R-013','deliver',{date:'2026-10-22',receiver:'Cliente'});
assert.equal(data.units[0].state,'En renta');
assert.throws(()=>applyOperation(data,'R-013','deliver',{date:'2026-10-22',receiver:'Cliente'}));
data=applyOperation(data,'R-013','signature',{name:'Cliente',date:'2026-10-22'});
data=applyOperation(data,'R-013','issue',{notes:'Se reporta ruido'});
data=applyOperation(data,'R-013','review',{mechanic:'Mecánico',notes:'Revisión con cliente'});
assert.equal(data.units[0].state,'En renta','Una falla o revisión con cliente no es una devolución');
data=applyOperation(data,'R-013','collection',{date:'2026-10-24',contact:'Cliente',time:'10:00'});
assert.equal(data.units[0].state,'En renta');
data=applyOperation(data,'R-013','return',{date:'2026-10-24',receiver:'Almacén'});
assert.equal(data.units[0].state,'En revisión');
assert.throws(()=>applyOperation(data,'R-013','close',{mechanic:'Mecánico',notes:'Baja',result:'Fuera de servicio'}),/autorizó/);
data=applyOperation(data,'R-013','close',{mechanic:'Mecánico',notes:'Equipo listo',result:'Disponible'});
assert.equal(data.units[0].state,'Disponible');assert.equal(data.rentals[0].status,'Cerrada');
assert.equal(data.rentals[0].issues.length,1);assert.equal(data.rentals[0].reviews.length,1);
assert.equal(new Set(data.units.map(u=>u.id)).size,data.units.length);
assert.notEqual(data.units[0].id,data.units[2].id);assert.equal(data.units[0].model,data.units[2].model);
assert.equal(JSON.parse(original).rentals[0].status,'Apartado');
assert.equal(loadData({getItem:()=>'{corrupt'}).version,2);
assert.deepEqual(loadData({getItem:()=>JSON.stringify(data)}),data);
console.log('Recorrido operativo, validaciones, unidades y almacenamiento correctos.');
